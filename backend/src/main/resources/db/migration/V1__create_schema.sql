-- MedAgenda initial schema.
-- Enum-like columns are VARCHAR + CHECK (mapped with @Enumerated(STRING)) instead of native
-- PostgreSQL enums: adding a value later is a simple constraint change, not an ALTER TYPE.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('PATIENT', 'DOCTOR', 'RECEPTIONIST', 'ADMIN'))
);

CREATE TABLE specialties (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL
);
-- Case-insensitive uniqueness: "Cardiologia" and "cardiologia" are the same specialty
CREATE UNIQUE INDEX uk_specialties_name ON specialties (lower(name));

CREATE TABLE health_insurances (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(80) NOT NULL,
    active BOOLEAN     NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uk_health_insurances_name ON health_insurances (lower(name));

CREATE TABLE doctors (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    crm          VARCHAR(12)  NOT NULL,
    specialty_id BIGINT       NOT NULL REFERENCES specialties (id),
    user_id      BIGINT       NOT NULL REFERENCES users (id),
    CONSTRAINT uk_doctors_crm UNIQUE (crm),
    CONSTRAINT uk_doctors_user UNIQUE (user_id)
);
CREATE INDEX ix_doctors_specialty ON doctors (specialty_id);

CREATE TABLE patients (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(120) NOT NULL,
    cpf                 VARCHAR(11)  NOT NULL, -- digits only
    phone               VARCHAR(11)  NOT NULL,
    birth_date          DATE         NOT NULL,
    health_insurance_id BIGINT REFERENCES health_insurances (id),
    user_id             BIGINT       NOT NULL REFERENCES users (id),
    CONSTRAINT uk_patients_cpf UNIQUE (cpf),
    CONSTRAINT uk_patients_user UNIQUE (user_id)
);

CREATE TABLE doctor_availabilities (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id             BIGINT      NOT NULL REFERENCES doctors (id) ON DELETE CASCADE,
    day_of_week           VARCHAR(9)  NOT NULL,
    start_time            TIME        NOT NULL,
    end_time              TIME        NOT NULL,
    slot_duration_minutes INTEGER     NOT NULL,
    CONSTRAINT ck_availability_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_availability_range CHECK (end_time > start_time),
    CONSTRAINT ck_availability_duration CHECK (slot_duration_minutes BETWEEN 5 AND 240),
    CONSTRAINT uk_availability_start UNIQUE (doctor_id, day_of_week, start_time)
);

CREATE TABLE appointments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   BIGINT        NOT NULL REFERENCES patients (id),
    doctor_id    BIGINT        NOT NULL REFERENCES doctors (id),
    -- Clinic-local date/time: the clinic works in a single time zone
    scheduled_at TIMESTAMP     NOT NULL,
    status       VARCHAR(20)   NOT NULL DEFAULT 'SCHEDULED',
    notes        VARCHAR(2000),
    created_at   TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_appointments_status CHECK (status IN
        ('SCHEDULED', 'CONFIRMED', 'CANCELLED', 'COMPLETED', 'NO_SHOW'))
);

-- Business rules "no double booking" enforced by the database itself, so two concurrent
-- requests cannot both succeed. Partial indexes ignore cancelled appointments, which frees
-- the slot to be booked again.
CREATE UNIQUE INDEX uk_appointments_doctor_slot
    ON appointments (doctor_id, scheduled_at) WHERE status <> 'CANCELLED';
CREATE UNIQUE INDEX uk_appointments_patient_slot
    ON appointments (patient_id, scheduled_at) WHERE status <> 'CANCELLED';

CREATE INDEX ix_appointments_scheduled_at ON appointments (scheduled_at);
CREATE INDEX ix_appointments_patient ON appointments (patient_id);
